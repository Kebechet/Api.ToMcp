        public static string Emit(ActionInfoModel action, GeneratorConfigModel config, string? overrideClassName = null)
        {
            return Emit(action, config.Naming, config.StructuredOutput, overrideClassName ?? action.ToolClassName);
        }

        public static string Emit(ToolSourceModel tool)
        {
            return Emit(tool.Action, tool.Naming, tool.StructuredOutput, tool.ClassName);
        }

        private static string Emit(ActionInfoModel action, NamingConfigModel naming, bool structuredOutput, string className)
        {
            var toolName = FormatToolName(action, naming);
            var fallbackDescription = action.IsMinimalApiEndpoint
                ? $"Invokes {action.HttpMethod} {action.RouteTemplate}"
                : $"Invokes {action.ControllerName}.{action.Name}";
            var description = action.CustomDescription ?? action.EndpointDescription ?? action.XmlDocSummary ?? fallbackDescription;

            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("using System.ComponentModel;");
            sb.AppendLine("using System.Text.Json;");
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine("using ModelContextProtocol.Server;");
            sb.AppendLine("using ModelContextProtocol.Protocol;");
            sb.AppendLine("using Api.ToMcp.Runtime;");
            sb.AppendLine("using Api.ToMcp.Abstractions.Scopes;");
            sb.AppendLine();
            sb.AppendLine("namespace Api.ToMcp.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    [McpServerToolType]");
            sb.AppendLine(action.HasNonPublicParameterTypes
                ? $"    internal static class {className}"
                : $"    public static class {className}");
            sb.AppendLine("    {");

            EmitToolMethod(sb, action, toolName, description, hasOutputSchema: structuredOutput && action.OutputSchemaType != null);

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static void EmitToolMethod(
            StringBuilder sb,
            ActionInfoModel action,
            string toolName,
            string description,
            bool hasOutputSchema)
        {
            var parameters = action.Parameters
                .Where(p => p.Source != ParameterSourceModel.Services)
                .ToList();
            var routeValues = ResolveRouteValues(action, parameters);
            var routeParameters = new HashSet<ParameterInfoModel>(routeValues.Arguments.Values.Where(x => x.IsRequired).Select(x => x.Parameter));

            // The MCP server injects the request's CancellationToken into any tool method that
            // declares one (bound by type, so it is not surfaced as a tool input parameter).
            // Emitted last so its default value doesn't violate parameter ordering.
            // MCP passes arguments by name, so the required parameters come first, wherever the action declares them:
            // a nullable one without a default is optional, and C# wants every optional parameter after the required ones.
            var names = new ToolNames(parameters);
            var paramDecls = new List<string> { $"IMcpHttpInvoker {names.Invoker}" };
            paramDecls.AddRange(parameters
                .Where(x => !IsOptional(x, routeParameters))
                .Concat(parameters.Where(x => IsOptional(x, routeParameters)))
                .Select(x => FormatParameterDeclaration(x, IsOptional(x, routeParameters))));
            paramDecls.Add($"System.Threading.CancellationToken {names.CancellationToken} = default");

            var annotations = FormatAnnotationArguments(action.Annotations);
            var title = FormatTitleArgument(action.Title);

            // A ToolName or a toolNameFormat is any string, so the name is written as an escaped C# literal.
            var toolNameLiteral = SymbolDisplay.FormatLiteral(toolName, quote: true);

            // AddMcpTools warns when such a tool is called through an invoker that cannot send headers or a form.
            var sendsHeadersOrForm = parameters.Any(x => x.Source is ParameterSourceModel.Header or ParameterSourceModel.Form);
            if (hasOutputSchema)
            {
                var sendsHeadersOrFormArgument = sendsHeadersOrForm ? ", " + SendsHeadersOrFormArgument : "";
                sb.AppendLine($"        [McpServerTool(Name = {toolNameLiteral}{title}, UseStructuredContent = true, OutputSchemaType = typeof({action.OutputSchemaType}), {annotations})]");
                sb.AppendLine($"        [{GeneratedToolAttribute}(IsOutputNullable = {FormatBool(action.IsOutputNullable)}{sendsHeadersOrFormArgument})]");
            }
            else
            {
                sb.AppendLine($"        [McpServerTool(Name = {toolNameLiteral}{title}, {annotations})]");
                if (sendsHeadersOrForm)
                {
                    sb.AppendLine($"        [{GeneratedToolAttribute}({SendsHeadersOrFormArgument})]");
                }
            }
            sb.AppendLine($"        [{RequiredScopeAttribute}({GetScopeExpression(action.RequiredScope, names.McpScope)})]");
            sb.AppendLine($"        [Description(\"{EscapeString(description)}\")]");
            // A tool with an output schema returns the parsed body on success, for the SDK to turn into structured content.
            sb.Append(hasOutputSchema
                ? "        public static async Task<object> InvokeAsync("
                : "        public static async Task<CallToolResult> InvokeAsync(");
            sb.AppendLine();

            for (int i = 0; i < paramDecls.Count; i++)
            {
                var comma = i < paramDecls.Count - 1 ? "," : "";
                sb.AppendLine($"            {paramDecls[i]}{comma}");
            }

            sb.AppendLine("        )");
            sb.AppendLine("        {");

            EmitRouteBuilding(sb, action, parameters, routeValues, names);
            var (hasHeaders, hasForm) = EmitHeadersAndForm(sb, parameters, routeValues, names);
            EmitHttpCall(sb, action, parameters, hasOutputSchema, names, hasHeaders, hasForm);

            sb.AppendLine("        }");
        }

        private static void EmitRouteBuilding(
            StringBuilder sb,
            ActionInfoModel action,
            List<ParameterInfoModel> parameters,
            RouteValues routeValues,
            ToolNames names)
        {
            // Generate route variables
            var routeVariables = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var part in routeValues.Parts.Where(x => x.IsParameter))
            {
                if (routeVariables.ContainsKey(part.Text) || !routeValues.Sources.TryGetValue(part.Text, out var source))
                    continue;

                var routeVariable = names.Declare(RouteVariablePrefix + source.VariableName);
                routeVariables[part.Text] = routeVariable;

                // A catch-all value spans path segments, which MVC reads back with their slashes.
                var keptSlashes = part.IsCatchAll ? ".Replace(\"%2F\", \"/\")" : "";
                sb.AppendLine($"            var {routeVariable} = {names.SystemNamespace}.Uri.EscapeDataString({RequestValueFormatter}.Format({source.Expression})){keptSlashes};");

                // Whatever the schema says, a client can send a value that sends the request to another path, one another
                // action of the same HTTP method may serve.
                var argument = routeValues.Arguments[part.Text];
                var message = FormatRouteValueRefusal(part, argument.Parameter, argument.IsProperty, argument.IsRequired);
                sb.AppendLine($"            if ({RequestValueFormatter}.ChangesThePath({routeVariable}, isRequired: {FormatBool(argument.IsRequired)}))");
                sb.AppendLine($"                return new CallToolResult {{ IsError = true, Content = {{ new TextContentBlock {{ Text = {SymbolDisplay.FormatLiteral(message, quote: true)} }} }} }};");
            }

            sb.AppendLine($"            var {names.Route} = {FormatRouteString(routeValues.Parts, routeVariables)};");

            // Build query string. MVC binds a simple type that names no route value from the query string on every
            // HTTP method: [ApiController] infers [FromQuery] for it, and in a controller without [ApiController] the
            // query string is one of the value providers. A complex type bound from those value providers is expanded
            // into it as [FromQuery] would expand it.
            var queryValues = new List<(string Key, string Expression)>();
            foreach (var param in parameters)
            {
                // [ApiController] infers [FromRoute] for a parameter its route names by the parameter's own name, else
                // [FromQuery] (InferParameterBindingInfoConvention), and MVC then reads it under the name it binds it under;
                // without [ApiController] MVC reads the route value of that name first.
                var isNamedByRoute = routeValues.Template.HasParameter(
                    param.Source == ParameterSourceModel.Auto && action.IsApiController ? param.Name : GetBinderModelName(param));
                if (param.Source == ParameterSourceModel.Query &&
                    (param.Properties.Any(x => routeValues.RouteProperties.Contains((param, x))) || (IsBoundWithoutPrefix(param) && !param.IsSimpleType)))
                {
                    queryValues.AddRange(GetQueryValues(param, routeValues.RouteProperties));
                }
                else if (param.Source == ParameterSourceModel.Custom && !isNamedByRoute)
                {
                    queryValues.Add((GetBinderModelName(param), GetModelBinderValue(param)));
                }
                else if (param.Source == ParameterSourceModel.Query ||
                    (param.Source == ParameterSourceModel.Auto && !isNamedByRoute && param.IsSimpleType))
                {
                    queryValues.Add((GetBinderModelName(param), GetSentValue(param)));
                }
                else if (param.Source == ParameterSourceModel.Route)
                {
                    // MVC reads a [FromQuery] property of a [FromRoute] parameter from the query string, under its own name,
                    // as no route value carries the parameter's; under o.c when [FromRoute(Name = "o")] names the parameter.
                    queryValues.AddRange(param.Properties
                        .Where(x => x.Source == ParameterSourceModel.Query)
                        .Select(x => (GetPropertyModelName(param, x), GetPropertyAccess(param, x))));
                }
                else if (param.Source == ParameterSourceModel.Auto && !isNamedByRoute && IsBoundFromValueProviders(param, action))
                {
                    queryValues.AddRange(GetQueryValues(param, routeValues.RouteProperties));
                }
            }

            if (queryValues.Any())
            {
                sb.AppendLine($"            var {names.QueryParts} = new {names.SystemNamespace}.Collections.Generic.List<string>();");
                foreach (var (key, expression) in queryValues)
                {
                    // A name a binding attribute gives, such as a [FromQuery(Name)] alias, is any string, so it is written as
                    // an escaped C# literal.
                    var queryKeyLiteral = SymbolDisplay.FormatLiteral(key, quote: true);
                    sb.AppendLine($"            {RequestValueFormatter}.AddQueryValue({names.QueryParts}, {queryKeyLiteral}, {expression});");
                }
                sb.AppendLine($"            if ({names.QueryParts}.Count > 0)");
                sb.AppendLine($"                {names.Route} += \"?\" + string.Join(\"&\", {names.QueryParts});");
            }
        }

        /// <summary>
        /// The headers and the form the tool sends: each <c>[FromHeader]</c> parameter as a header, refusing a value no
        /// header can hold before the API is called, and each <c>[FromForm]</c> one as form fields, under the keys MVC's
        /// form binding reads, refusing a date the calendar of the culture the form is written in cannot hold.
        /// </summary>
        private static (bool HasHeaders, bool HasForm) EmitHeadersAndForm(
            StringBuilder sb,
            List<ParameterInfoModel> parameters,
            RouteValues routeValues,
            ToolNames names)
        {
            var headerParameters = parameters.Where(x => x.Source == ParameterSourceModel.Header).ToList();
            if (headerParameters.Any())
            {
                sb.AppendLine($"            var {names.Headers} = new {names.SystemNamespace}.Collections.Generic.List<{names.SystemNamespace}.Collections.Generic.KeyValuePair<string, string>>();");
                foreach (var parameter in headerParameters)
                {
                    var headerName = GetBinderModelName(parameter);
                    var message = parameter.IsCollection
                        ? $"The argument '{parameter.Name}' is sent as the request header '{headerName}', one value per item, and an item cannot be empty and can hold only visible ASCII characters other than '\"', spaces and tabs."
                        : $"The argument '{parameter.Name}' is sent as the request header '{headerName}', which can hold only visible ASCII characters, spaces and tabs.";
                    sb.AppendLine($"            if (!{RequestValueFormatter}.TryAddHeaderValue({names.Headers}, {SymbolDisplay.FormatLiteral(headerName, quote: true)}, {GetSentValue(parameter)}))");
                    sb.AppendLine($"                return new CallToolResult {{ IsError = true, Content = {{ new TextContentBlock {{ Text = {SymbolDisplay.FormatLiteral(message, quote: true)} }} }} }};");
                }
            }

            var formParameters = parameters.Where(x => x.Source == ParameterSourceModel.Form).ToList();
            if (formParameters.Any())
            {
                sb.AppendLine($"            var {names.FormParts} = new {names.SystemNamespace}.Collections.Generic.List<string>();");
                sb.AppendLine($"            {names.SystemNamespace}.Globalization.CultureInfo? {names.FormCulture} = null;");
                foreach (var parameter in formParameters)
                {
                    var message = $"The argument '{parameter.Name}' holds a date that the tool cannot write in the calendar of the MCP request's culture, in which it writes the form. Give a date that calendar holds; a date left out counts as 0001-01-01.";
                    foreach (var (key, expression) in GetFormValues(parameter, routeValues.RouteProperties))
                    {
                        sb.AppendLine($"            if (!{RequestValueFormatter}.TryAddFormValue({names.FormParts}, {SymbolDisplay.FormatLiteral(key, quote: true)}, {expression}, ref {names.FormCulture}))");
                        sb.AppendLine($"                return new CallToolResult {{ IsError = true, Content = {{ new TextContentBlock {{ Text = {SymbolDisplay.FormatLiteral(message, quote: true)} }} }} }};");
                    }
                }
            }

            return (headerParameters.Any(), formParameters.Any());
        }

        /// <summary>
        /// The form values of a <c>[FromForm]</c> parameter: the whole value under the name MVC binds it under, which it
        /// reads a complex type's properties under as a prefix. When a <c>[FromRoute]</c> property of it fills the route, MVC
        /// binds that property only without the prefix, and with an empty name, <c>[Bind(Prefix = "")]</c>, every property,
        /// so the others go under their own names: those it reads from the form, a property without a binding attribute or
        /// with <c>[FromForm]</c>.
        /// </summary>
        private static IEnumerable<(string Key, string Expression)> GetFormValues(
            ParameterInfoModel parameter,
            HashSet<(ParameterInfoModel Parameter, PropertyInfoModel Property)> routeProperties)
        {
            if ((!IsBoundWithoutPrefix(parameter) || parameter.IsSimpleType) && !parameter.Properties.Any(x => routeProperties.Contains((parameter, x))))
            {
                return new[] { (GetBinderModelName(parameter), GetSentValue(parameter)) };
            }

            return parameter.Properties
                .Where(x => x.Source is ParameterSourceModel.Auto or ParameterSourceModel.Form && !routeProperties.Contains((parameter, x)))
                .Select(x => (GetBinderModelName(x), GetPropertyAccess(parameter, x)));
        }

        /// <summary>
        /// Why the tool cannot build the URL MVC serves the action at, or send what it reads, as a clause of MCP009's
        /// message, or null when it can.
        /// </summary>
        internal static string? GetUnbuildableRouteReason(ActionInfoModel action)
        {
            if (action.RouteProblem != null)
            {
                return action.RouteProblem;
            }

            if (action.ParameterProblem != null)
            {
                return action.ParameterProblem;
            }

            var parameters = action.Parameters
                .Where(p => p.Source != ParameterSourceModel.Services)
                .ToList();
            var unfilledName = ResolveRouteValues(action, parameters).UnfilledName;
            if (unfilledName is null)
            {
                return null;
            }

            // The URL leaves out an optional route value at its end that nothing fills, unless that URL may be another
            // action's.
            var reason = $"no parameter or property fills the route value '{{{unfilledName}}}' of {action.HttpMethod} {action.RouteTemplate}";
            return action.RouteEnd == RouteEndModel.Required
                ? reason + ", which the URL needs, as another action may be served at the URL without it"
                : reason;
        }

        /// <summary>
        /// What fills each route value of the action's URL, and the URL's parts without the optional route values at its end
        /// that nothing fills, which MVC serves the action without.
        /// </summary>
        private static RouteValues ResolveRouteValues(ActionInfoModel action, List<ParameterInfoModel> parameters)
        {
            var template = RouteTemplate.Parse(action.RouteTemplate);
            var routePlaceholders = template.ParameterNames;
            var lastPart = template.Parts.Count == 0 ? null : template.Parts[template.Parts.Count - 1];
            var isEndRequired = action.RouteEnd == RouteEndModel.Required;

            // Build mapping from placeholder to source expression
            var placeholderSources = new Dictionary<string, (string Expression, string VariableName)>(StringComparer.OrdinalIgnoreCase);
            var placeholderArguments = new Dictionary<string, (ParameterInfoModel Parameter, bool IsProperty)>(StringComparer.OrdinalIgnoreCase);

            // Of a parameter bound from the route, query and form values, MVC reads a [FromRoute] property only from the
            // route value of its name, and only when the parameter carries no prefix, whichever parameter fills that route
            // value. An unattributed property it reads from that route value without the prefix too, but from its prefixed
            // key in the query string with it, so its parameter keeps the prefix unless that property fills the route
            // value. A property in this set is sent only in the route, and the other properties of its parameter under
            // their own names. A [FromQuery] parameter that names no prefix of its own MVC binds the same way from the query
            // string, where only a [FromRoute] property reads the route. A parameter whose binding attribute names it, such
            // as [Bind(Prefix = "f")], MVC always binds under that prefix, so none of its properties reads the route.
            var valueProviderParams = parameters.Where(p => IsBoundFromValueProviders(p, action) && string.IsNullOrEmpty(p.ModelName)).ToList();
            var unprefixableParams = parameters.Where(p => FallsBackToNoPrefix(p, action)).ToList();
            var routeProperties = new HashSet<(ParameterInfoModel Parameter, PropertyInfoModel Property)>(unprefixableParams
                .SelectMany(p => p.Properties.Select(prop => (Parameter: p, Property: prop)))
                .Where(x => x.Property.Source == ParameterSourceModel.Route && routePlaceholders.Any(placeholder => ReadsRouteValue(x.Property, placeholder))));

            // MVC fills a parameter it reads from the route from the route value of the name it binds the parameter under:
            // the name a binding attribute gives, [FromRoute(Name = "productId")] say, else the parameter's own
            // (case-insensitive). One it binds under that name from the query string or a header does not take the route
            // value from the parameter MVC reads it into.
            var namedParams = routePlaceholders.ToDictionary(
                placeholder => placeholder,
                placeholder => parameters.FirstOrDefault(p => IsReadFromRouteValue(p, action, template) &&
                    string.Equals(GetBinderModelName(p), placeholder, StringComparison.OrdinalIgnoreCase)),
                StringComparer.OrdinalIgnoreCase);

            foreach (var placeholder in routePlaceholders)
            {
                var directParam = namedParams[placeholder];

                // Else a property MVC reads from the route value: of a [FromRoute] parameter without a name of its own
                // first, then of one bound from the route, query and form values, a [FromRoute] one before an unattributed
                // one.
                var routeProperty = directParam is null
                    ? parameters
                        .Where(p => p.Source == ParameterSourceModel.Route && string.IsNullOrEmpty(p.ModelName))
                        .Select(p => (Parameter: p, Property: p.Properties.FirstOrDefault(prop => ReadsRouteValue(prop, placeholder))))
                        .Concat(unprefixableParams.Select(p => (Parameter: p, Property: p.Properties.FirstOrDefault(prop =>
                            prop.Source == ParameterSourceModel.Route && ReadsRouteValue(prop, placeholder)))))
                        .Concat(valueProviderParams.Select(p => (Parameter: p, Property: p.Properties.FirstOrDefault(prop =>
                            prop.Source == ParameterSourceModel.Auto && ReadsRouteValue(prop, placeholder)))))
                        .FirstOrDefault(x => x.Property is not null)
                    : default;

                // Failing those, something of the placeholder's name fills it, which MVC reads from elsewhere but the URL
                // needs a segment for: a property of a [FromBody] parameter, which MVC reads from the body, first.
                var bodyProperty = directParam is null && routeProperty.Property is null
                    ? parameters
                        .Where(p => p.Source == ParameterSourceModel.Body)
                        .Select(p => (Parameter: p, Property: p.Properties.FirstOrDefault(prop =>
                            string.Equals(prop.Name, placeholder, StringComparison.OrdinalIgnoreCase))))
                        .FirstOrDefault(x => x.Property is not null)
                    : default;

                // Then a parameter MVC binds under another name, from the query string say, unless that name fills another
                // route value: both would get its value, which may not even match this one's constraint. Then a simple one
                // MVC binds under the placeholder's name from elsewhere, as [ApiController] does a [ModelBinder(Name)] one
                // whose own name the route lacks; the prefix of a complex one names its properties, not a value.
                if (directParam is null && routeProperty.Property is null && bodyProperty.Property is null)
                {
                    directParam = parameters.FirstOrDefault(p =>
                            string.Equals(p.Name, placeholder, StringComparison.OrdinalIgnoreCase) && !namedParams.ContainsValue(p)) ??
                        parameters.FirstOrDefault(p =>
                            p.IsSimpleType && string.Equals(GetBinderModelName(p), placeholder, StringComparison.OrdinalIgnoreCase));
                }

                if (directParam != null)
                {
                    // An optional route value at the end of the URL, without a default of the route's own, MVC binds as
                    // the action's default when the URL leaves it out, as it does a query value. Only a whole segment is
                    // left out so: of {name}.{ext?}, the tool sends the value it is given, and leaves out the dot only
                    // with an empty one.
                    var partBefore = template.Parts.Count < 2 ? null : template.Parts[template.Parts.Count - 2];
                    var canBeLeftOut = !isEndRequired &&
                        lastPart is { IsParameter: true, IsOptional: true, HasDefaultValue: false } &&
                        string.Equals(lastPart.Text, placeholder, StringComparison.OrdinalIgnoreCase) &&
                        partBefore is { IsParameter: false } && partBefore.Text.EndsWith(PathSeparator, StringComparison.Ordinal);
                    placeholderSources[placeholder] = (canBeLeftOut ? GetSentValue(directParam) : EscapeIdentifier(directParam.Name), directParam.Name);
                    placeholderArguments[placeholder] = (directParam, IsProperty: false);
                }
                else
                {
                    // Then any property of the placeholder's name.
                    var propertySource = routeProperty.Property is not null ? routeProperty
                        : bodyProperty.Property is not null ? bodyProperty
                        : parameters
                            .Select(p => (Parameter: p, Property: p.Properties.FirstOrDefault(prop => IsNamedBy(prop, placeholder))))
                            .FirstOrDefault(x => x.Property != null);

                    if (propertySource.Property != null)
                    {
                        placeholderSources[placeholder] = GetRouteValueSource(propertySource.Parameter, propertySource.Property);
                        placeholderArguments[placeholder] = (propertySource.Parameter, IsProperty: true);

                        if (valueProviderParams.Contains(propertySource.Parameter) && ReadsRouteValue(propertySource.Property, placeholder))
                        {
                            routeProperties.Add((propertySource.Parameter, propertySource.Property));
                        }
                    }
                }
            }

            var parts = template.Parts.ToList();
            if (!isEndRequired)
            {
                RemoveUnfilledOptionalEnd(parts, placeholderSources);
            }

            // A URL without a value the template requires matches another route, possibly another action's of the same
            // HTTP method: DELETE api/items/ instead of DELETE api/items/{id}. So may one without the optional value at its
            // end, and one that another route of the same action leaves out is served by the action anyway.
            bool IsRequired(RouteTemplatePart part)
            {
                if (!ReferenceEquals(part, lastPart) || action.RouteEnd == RouteEndModel.AsTemplate)
                {
                    return !part.IsOptional;
                }

                return isEndRequired;
            }

            var arguments = placeholderArguments.ToDictionary(
                x => x.Key,
                x => (x.Value.Parameter, x.Value.IsProperty, IsRequired: template.Parts.Any(part =>
                    part.IsParameter && IsRequired(part) && string.Equals(part.Text, x.Key, StringComparison.OrdinalIgnoreCase))),
                StringComparer.OrdinalIgnoreCase);

            return new RouteValues(
                template,
                parts,
                placeholderSources,
                routeProperties,
                arguments,
                parts.FirstOrDefault(x => x.IsParameter && !placeholderSources.ContainsKey(x.Text))?.Text);
        }

        /// <summary>
        /// The error a tool returns instead of a URL whose path a route value would change, as
        /// <c>McpRequestValueFormatter.ChangesThePath</c> tells. It names the argument as the input schema does: a
        /// parameter by its own name, never the property of one, which the SDK's JSON options name in the schema.
        /// </summary>
        private static string FormatRouteValueRefusal(RouteTemplatePart part, ParameterInfoModel parameter, bool isProperty, bool isRequired)
        {
            var refusedValues = (isRequired, part.IsCatchAll) switch
            {
                (true, false) => "be empty, '.' or '..'",
                (true, true) => "be empty or have a '.' or '..' segment",
                (false, false) => "be '.' or '..'",
                (false, true) => "have a '.' or '..' segment"
            };

            var filler = isProperty ? $"The argument '{parameter.Name}' has a property that fills" : $"The argument '{parameter.Name}' fills";

            return $"{filler} the route value {{{part.Text}}} of the API's URL, which cannot {refusedValues}.";
        }

        /// <summary>
        /// Leaves out the optional route values nothing fills at the end of the URL, each with the separator before it:
        /// MVC serves <c>z/{id?}</c> at <c>z</c>, and <c>{name}.{ext?}</c> at <c>{name}</c>.
        /// </summary>
        private static void RemoveUnfilledOptionalEnd(List<RouteTemplatePart> parts, Dictionary<string, (string Expression, string VariableName)> sources)
        {
            while (parts.Count > 0 && parts[parts.Count - 1] is { IsParameter: true, IsOptional: true } last && !sources.ContainsKey(last.Text))
            {
                parts.RemoveAt(parts.Count - 1);
                if (parts.Count == 0 || parts[parts.Count - 1].IsParameter)
                    continue;

                var text = parts[parts.Count - 1].Text;
                if (!text.EndsWith(PathSeparator, StringComparison.Ordinal) && !text.EndsWith(ComplexSegmentSeparator, StringComparison.Ordinal))
                    break;

                parts.RemoveAt(parts.Count - 1);
                if (text.Length > 1)
                    parts.Add(RouteTemplatePart.Literal(text.Substring(0, text.Length - 1)));
            }
        }

        /// <summary>
        /// Whether the part is the dot between a route value and an optional one that ends their segment, as in
        /// <c>{name}.{ext?}</c>: the only text MVC lets come before an optional route value in a segment of several.
        /// </summary>
        private static bool IsOptionalSeparator(IReadOnlyList<RouteTemplatePart> parts, int index)
        {
            return parts[index] is { IsParameter: false, Text: ComplexSegmentSeparator } &&
                index > 0 && parts[index - 1].IsParameter &&
                index + 1 < parts.Count && parts[index + 1] is { IsParameter: true, IsOptional: true } &&
                (index + 2 == parts.Count || parts[index + 2].Text.StartsWith(PathSeparator, StringComparison.Ordinal));
        }

        /// <summary>
        /// The URL as an interpolated string of the route's literal text and the variables of its route values. The text
        /// is escaped as a C# literal, its braces doubled, so any template compiles.
        /// </summary>
        private static string FormatRouteString(IReadOnlyList<RouteTemplatePart> parts, Dictionary<string, string> routeVariables)
        {
            var route = new StringBuilder();
            for (var i = 0; i < parts.Count; i++)
            {
                var part = parts[i];

                // The generator gives no tool to an action with a route value nothing fills, so every one has a variable.
                if (part.IsParameter)
                {
                    if (routeVariables.TryGetValue(part.Text, out var routeVariable))
                        route.Append('{').Append(routeVariable).Append('}');

                    continue;
                }

                // MVC matches the dot before an optional route value that ends a segment of several only together with a
                // value: it serves {name}.{ext?} at report, and answers report. with 404.
                if (IsOptionalSeparator(parts, i) && routeVariables.TryGetValue(parts[i + 1].Text, out var optionalVariable))
                {
                    route.Append("{(").Append(optionalVariable).Append(".Length == 0 ? \"\" : \"").Append(ComplexSegmentSeparator).Append("\")}");
                    continue;
                }

                var literal = SymbolDisplay.FormatLiteral(part.Text, quote: true);
                route.Append(literal.Substring(1, literal.Length - 2).Replace("{", "{{").Replace("}", "}}"));
            }

            return "$\"" + (route.Length == 0 ? PathSeparator : route.ToString()) + "\"";
        }

        /// <summary>
        /// The value of a parameter the tool sends as a query value, or as an optional route value at the end of the URL:
        /// nothing when it equals the action's default. MVC applies that default itself to a value it is not sent, and it
        /// may refuse the same value as text, such as an enum value that no member has.
        /// </summary>
        private static string GetSentValue(ParameterInfoModel parameter)
        {
            var name = EscapeIdentifier(parameter.Name);

            // MVC answers a parameter it requires a value for with 400 when it is not sent, whatever its default. One it may
            // require is sent too, unless MVC refuses its default as text, which then fails for sure.
            if (parameter.IsBindingRequired || (parameter.IsBindingRequirementUnknown && !parameter.IsDefaultRefusedAsText))
            {
                return name;
            }

            return parameter.DefaultValueExpression is { } defaultValue && defaultValue != NullLiteral
                ? $"{name} == {defaultValue} ? null : {name}"
                : name;
        }

        /// <summary>
        /// The value of a parameter with a model binder of its own, which reads one value under the parameter's model name:
        /// written whole, as a route value is, rather than property by property, which no binder reads. A collection's
        /// items repeat the key, as MVC hands such a binder all the values of a key.
        /// </summary>
        private static string GetModelBinderValue(ParameterInfoModel parameter)
        {
            if (parameter.IsCollection)
            {
                return GetSentValue(parameter);
            }

            var name = EscapeIdentifier(parameter.Name);
            var formattedValue = $"{RequestValueFormatter}.Format({name})";

            return parameter.IsValueType && !parameter.IsNullable && !parameter.HasDefaultValue
                ? formattedValue
                : $"{name} is null ? null : {formattedValue}";
        }

        /// <summary>
        /// Whether MVC binds a complex parameter property by property from the route, query and form values: in a
        /// controller without <c>[ApiController]</c> it does for every one, and in an <c>[ApiController]</c> for one whose
        /// type has a property with a binding source of its own, which keeps it from inferring the body.
        /// </summary>
        private static bool IsBoundFromValueProviders(ParameterInfoModel parameter, ActionInfoModel action)
        {
            return parameter.Source == ParameterSourceModel.Auto &&
                !parameter.IsSimpleType &&
                (!action.IsApiController || parameter.HasBindingSourceProperties);
        }

        /// <summary>
        /// Whether MVC binds a complex parameter under its name as a prefix only when a value carries it, and under the
        /// names of its properties otherwise (<c>ParameterBinder</c>): one bound from the route, query and form values, or a
        /// <c>[FromQuery]</c> or <c>[FromForm]</c> one, unless a binding attribute names it, <c>[Bind(Prefix = "f")]</c> say,
        /// which MVC then always binds it under. An empty name, <c>[Bind(Prefix = "")]</c>, it always binds without a prefix.
        /// </summary>
        private static bool FallsBackToNoPrefix(ParameterInfoModel parameter, ActionInfoModel action)
        {
            return string.IsNullOrEmpty(parameter.ModelName) &&
                (IsBoundFromValueProviders(parameter, action) ||
                    (parameter.Source is ParameterSourceModel.Query or ParameterSourceModel.Form && !parameter.IsSimpleType));
        }

        /// <summary>
        /// Whether a binding attribute gives the parameter an empty name, under which MVC binds its properties without a
        /// prefix, as MVC takes the first name that is not null.
        /// </summary>
        private static bool IsBoundWithoutPrefix(ParameterInfoModel parameter)
        {
            return parameter.ModelName is not null && parameter.ModelName.Length == 0;
        }

        /// <summary>
        /// Whether MVC reads the parameter as one value from the route value its binding name names: a <c>[FromRoute]</c>
        /// one of a type it reads from one string, one with a model binder of its own, or a simple one without a binding
        /// source, which an <c>[ApiController]</c> reads from the route only when the route names the parameter's own name
        /// (<c>InferParameterBindingInfoConvention</c>). A complex parameter's name is the prefix of its properties, not a
        /// value; one MVC reads from the query string, a header or the body takes no route value.
        /// </summary>
        private static bool IsReadFromRouteValue(ParameterInfoModel parameter, ActionInfoModel action, RouteTemplate template)
        {
            switch (parameter.Source)
            {
                case ParameterSourceModel.Custom:
                    return true;
                case ParameterSourceModel.Route:
                    return parameter.IsSimpleType;
                case ParameterSourceModel.Auto:
                    return parameter.IsSimpleType && (!action.IsApiController || template.HasParameter(parameter.Name));
                default:
                    return false;
            }
        }

        /// <summary>
        /// The query values of a parameter bound from the route, query and form values, or from the query string alone. MVC reads its properties under the
        /// parameter's name as a prefix (<c>filter.City</c>) when a value carries it, and under their own names otherwise;
        /// under the name a binding attribute gives the parameter always (<c>f.City</c>), and under their own names always
        /// when that name is empty. Only unprefixed names let a property fill a route value, as no route value is named
        /// <c>filter.Id</c>, so a parameter with such a property, or with an empty name, sends its properties under their
        /// own names, each where MVC reads it: a <c>[FromQuery]</c> one or one without a binding attribute in the query
        /// string, any other not at all.
        /// </summary>
        private static IEnumerable<(string Key, string Expression)> GetQueryValues(
            ParameterInfoModel parameter,
            HashSet<(ParameterInfoModel Parameter, PropertyInfoModel Property)> routeProperties)
        {
            if (!IsBoundWithoutPrefix(parameter) && !parameter.Properties.Any(x => routeProperties.Contains((parameter, x))))
            {
                return new[] { (GetBinderModelName(parameter), EscapeIdentifier(parameter.Name)) };
            }

            return parameter.Properties
                .Where(x => x.Source is ParameterSourceModel.Auto or ParameterSourceModel.Query && !routeProperties.Contains((parameter, x)))
                .Select(x => (GetBinderModelName(x), GetPropertyAccess(parameter, x)));
        }

        private static (string Expression, string VariableName) GetRouteValueSource(ParameterInfoModel parameter, PropertyInfoModel property)
        {
            return (GetPropertyAccess(parameter, property), $"{parameter.Name}_{property.Name}");
        }

        /// <summary>
        /// Whether MVC reads a property from the route value a placeholder names: a [FromRoute] one, or one without a
        /// binding attribute, which reads every value provider, by the name it binds it under.
        /// </summary>
        private static bool ReadsRouteValue(PropertyInfoModel property, string placeholder)
        {
            return property.Source is ParameterSourceModel.Auto or ParameterSourceModel.Route &&
                string.Equals(GetBinderModelName(property), placeholder, StringComparison.OrdinalIgnoreCase);
        }

        private static bool IsNamedBy(PropertyInfoModel property, string placeholder)
        {
            return string.Equals(GetBinderModelName(property), placeholder, StringComparison.OrdinalIgnoreCase) ||
                string.Equals(property.Name, placeholder, StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// A nullable parameter's property is read with <c>?.</c>, which the formatter takes as no value.
        /// </summary>
        private static string GetPropertyAccess(ParameterInfoModel parameter, PropertyInfoModel property)
        {
            return parameter.IsNullable
                ? $"{EscapeIdentifier(parameter.Name)}?.{EscapeIdentifier(property.Name)}"
                : $"{EscapeIdentifier(parameter.Name)}.{EscapeIdentifier(property.Name)}";
        }

        /// <summary>
        /// A parameter or property name as a C# identifier. A keyword such as <c>event</c>, which a C# name declares as
        /// <c>@event</c>, gets the <c>@</c> back, as does <c>await</c>, a keyword inside the async method a tool is.
        /// </summary>
        private static string EscapeIdentifier(string name)
        {
            return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) == SyntaxKind.AwaitKeyword
                ? "@" + name
                : name;
        }

        private static string GetBinderModelName(PropertyInfoModel property)
        {
            return property.ModelName ?? property.Name;
        }

        /// <summary>
        /// The name MVC binds the parameter under, which the tool sends its value under; its argument keeps its own name.
        /// </summary>
        private static string GetBinderModelName(ParameterInfoModel parameter)
        {
            return parameter.ModelName ?? parameter.Name;
        }

        /// <summary>
        /// The key MVC reads a property of a parameter bound without a prefix under, unless a binding attribute names the
        /// parameter: then under that name as the prefix, <c>o.c</c> (<c>ModelNames.CreatePropertyModelName</c>).
        /// </summary>
        private static string GetPropertyModelName(ParameterInfoModel parameter, PropertyInfoModel property)
        {
            return string.IsNullOrEmpty(parameter.ModelName)
                ? GetBinderModelName(property)
                : parameter.ModelName + PropertyModelNameSeparator + GetBinderModelName(property);
        }

        private static void EmitHttpCall(
            StringBuilder sb,
            ActionInfoModel action,
            List<ParameterInfoModel> parameters,
            bool hasOutputSchema,
            ToolNames names,
            bool hasHeaders,
            bool hasForm)
        {
            var bodyParam = parameters.FirstOrDefault(p => p.Source == ParameterSourceModel.Body);
            var invoker = names.Invoker;
            var route = names.Route;
            var cancellationToken = names.CancellationToken;

            sb.AppendLine($"            await {invoker}.BeforeInvokeAsync({GetScopeExpression(action.RequiredScope, names.McpScope)}, {cancellationToken});");

            string invokerCall;
            if (hasHeaders || hasForm)
            {
                // IMcpHttpInvoker has no method that sends headers or a form, and a member added to it would break every
                // implementation, so the request goes through McpHttpRequest, which asks the invoker for the interface
                // that sends them.
                var httpMethodName = GetHttpMethodPropertyName(action.HttpMethod);
                if (httpMethodName is null)
                {
                    return;
                }

                var initializers = new List<string>();
                if (bodyParam != null && action.HttpMethod is HttpMethodNames.Post or HttpMethodNames.Put or HttpMethodNames.Patch)
                {
                    sb.AppendLine($"            var {names.BodyJson} = {names.JsonSerializer}.Serialize({EscapeIdentifier(bodyParam.Name)});");
                    initializers.Add($"JsonBody = {names.BodyJson}");
                }

                if (hasHeaders)
                {
                    // The invoker refuses a header the app trusts from its proxy under a name only the app's options give,
                    // and its error result names the argument the AI gave.
                    var headerArguments = parameters
                        .Where(x => x.Source == ParameterSourceModel.Header)
                        .Select(x => $"[{SymbolDisplay.FormatLiteral(GetBinderModelName(x), quote: true)}] = {SymbolDisplay.FormatLiteral(x.Name, quote: true)}");
                    initializers.Add($"Headers = {names.Headers}");
                    initializers.Add($"HeaderArguments = new {names.SystemNamespace}.Collections.Generic.Dictionary<string, string> {{ {string.Join(", ", headerArguments)} }}");
                }

                if (hasForm)
                {
                    initializers.Add($"FormBody = string.Join(\"&\", {names.FormParts})");
                    initializers.Add($"FormCulture = {names.FormCulture}");
                }

                sb.AppendLine($"            var {names.Request} = new {HttpRequestType}({names.SystemNamespace}.Net.Http.HttpMethod.{httpMethodName}, {route}) {{ {string.Join(", ", initializers)} }};");
                invokerCall = $"await {names.Request}.SendAsync({invoker}, {cancellationToken})";
                sb.AppendLine(hasOutputSchema
                    ? $"            return {StructuredOutput}.FromResult({invokerCall});"
                    : $"            return {invokerCall};");
                return;
            }

            switch (action.HttpMethod)
            {
                case HttpMethodNames.Get:
                    invokerCall = $"await {invoker}.GetAsync({route}, {cancellationToken})";
                    break;
                case HttpMethodNames.Post:
                case HttpMethodNames.Put:
                case HttpMethodNames.Patch:
                    var invokerMethod = action.HttpMethod == HttpMethodNames.Post ? "PostAsync" : action.HttpMethod == HttpMethodNames.Put ? "PutAsync" : "PatchAsync";
                    if (bodyParam != null)
                    {
                        sb.AppendLine($"            var {names.BodyJson} = {names.JsonSerializer}.Serialize({EscapeIdentifier(bodyParam.Name)});");
                    }
                    invokerCall = $"await {invoker}.{invokerMethod}({route}, {(bodyParam != null ? names.BodyJson : NullLiteral)}, {cancellationToken})";
                    break;
                case HttpMethodNames.Delete:
                    invokerCall = $"await {invoker}.DeleteAsync({route}, {cancellationToken})";
                    break;
                default:
                    return;
            }

            sb.AppendLine(hasOutputSchema
                ? $"            return {StructuredOutput}.FromResult({invokerCall});"
                : $"            return {invokerCall};");
        }

        /// <summary>
        /// The property of <c>System.Net.Http.HttpMethod</c> for an HTTP method a tool sends, or null for another.
        /// </summary>
        private static string? GetHttpMethodPropertyName(string httpMethod)
        {
            switch (httpMethod)
            {
                case HttpMethodNames.Get:
                    return "Get";
                case HttpMethodNames.Post:
                    return "Post";
                case HttpMethodNames.Put:
                    return "Put";
                case HttpMethodNames.Patch:
                    return "Patch";
                case HttpMethodNames.Delete:
                    return "Delete";
                default:
                    return null;
            }
        }

        /// <summary>
        /// McpScope is a [Flags] enum, so the <c>ToString()</c> of a combined value is "Read, Write", which is not C#.
        /// A combination of named flags is written as <c>McpScope.Read | McpScope.Write</c>, and a value with bits no
        /// flag names as a cast, so the generated tool always compiles.
        /// </summary>
        private static string GetScopeExpression(McpScopeModel scope, string mcpScope)
        {
            if (Enum.IsDefined(typeof(McpScopeModel), scope))
            {
                return $"{mcpScope}.{scope}";
            }

            var includedFlags = SingleScopes
                .Where(x => (scope & x) == x)
                .ToList();
            var includedBits = includedFlags.Aggregate(McpScopeModel.None, (combined, x) => combined | x);
            if (includedBits != scope)
            {
                return $"({mcpScope}){(int)scope}";
            }

            return string.Join(" | ", includedFlags.Select(x => $"{mcpScope}.{x}"));
        }

        private static string FormatAnnotationArguments(ToolAnnotationsModel annotations)
        {
            return $"ReadOnly = {FormatBool(annotations.IsReadOnly)}, Destructive = {FormatBool(annotations.IsDestructive)}, Idempotent = {FormatBool(annotations.IsIdempotent)}, OpenWorld = {FormatBool(annotations.IsOpenWorld)}";
        }

        /// <summary>
        /// The <c>Title</c> argument, which the SDK sends as <c>annotations.title</c>. A title is free text from
        /// <c>[McpExpose(Title)]</c>, so it is written as an escaped C# literal.
        /// </summary>
        private static string FormatTitleArgument(string title)
        {
            return string.IsNullOrEmpty(title)
                ? ""
                : $", Title = {SymbolDisplay.FormatLiteral(title, quote: true)}";
        }

        private static string FormatBool(bool value)
        {
            return value ? "true" : "false";
        }

        /// <summary>
        /// The registration of the tool classes, by their names as <see cref="GetUniqueToolClassNames"/> gives them.
        /// </summary>
        public static string EmitRegistration(IEnumerable<string> toolClassNames)
        {
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("namespace Api.ToMcp.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    public static class McpToolsInfo");
            sb.AppendLine("    {");
            sb.AppendLine("        public static readonly System.Type[] ToolTypes = new System.Type[]");
            sb.AppendLine("        {");

            foreach (var toolClassName in toolClassNames)
            {
                sb.AppendLine($"            typeof({toolClassName}),");
            }

            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        /// <summary>
        /// The class name of each action's tool, in the actions' order: its <see cref="ActionInfoModel.ToolClassName"/>, with
        /// a number from 2 up for each further action with the same one, such as an overload.
        /// </summary>
        internal static List<string> GetUniqueToolClassNames(IEnumerable<ActionInfoModel> actions)
        {
            var uniqueClassNames = new List<string>();
            var counts = new Dictionary<string, int>(StringComparer.Ordinal);

            foreach (var action in actions)
            {
                var baseClassName = action.ToolClassName;
                if (counts.TryGetValue(baseClassName, out var count))
                {
                    counts[baseClassName] = count + 1;
                    uniqueClassNames.Add($"{baseClassName}_{count + 1}");
                }
                else
                {
                    counts[baseClassName] = 1;
                    uniqueClassNames.Add(baseClassName);
                }
            }

            return uniqueClassNames;
        }

        internal static string FormatToolName(ActionInfoModel action, NamingConfigModel naming)
        {
            var customName = action.CustomToolName;
            if (!string.IsNullOrEmpty(customName))
                return customName!;

            var controller = action.ControllerName;
            var actionName = action.Name;

            if (naming.RemoveControllerSuffix && controller.EndsWith(ConventionNames.ControllerSuffix))
                controller = controller.Substring(0, controller.Length - ConventionNames.ControllerSuffix.Length);

            return naming.ToolNameFormat
                .Replace("{Controller}", controller)
                .Replace("{Action}", actionName);
        }

        /// <summary>
        /// Whether the tool declares the parameter with a default value, which the MCP SDK leaves out of the input
        /// schema's <c>required</c>: the action's own default, else <c>null</c> for a nullable type. Never one that fills a
        /// route value the template requires, of <paramref name="routeParameters"/>, as no URL of the action leaves it out.
        /// </summary>
        private static bool IsOptional(ParameterInfoModel param, HashSet<ParameterInfoModel> routeParameters)
        {
            return (param.HasDefaultValue || param.IsNullable) && !routeParameters.Contains(param);
        }

        private static string FormatParameterDeclaration(ParameterInfoModel param, bool isOptional)
        {
            var type = param.Type;

            // A struct with a default is made nullable, so a call can leave it out and the action falls back to its own
            // default; a struct's default(T) has no constant, so it becomes null. A reference type whose default is null
            // is annotated, as a nullable-oblivious project declares it without the annotation.
            if (param.HasDefaultValue && !param.IsNullable && (param.IsValueType || param.DefaultValueExpression == NullLiteral))
            {
                type += "?";
            }

            var defaultPart = "";
            if (isOptional && param.HasDefaultValue)
            {
                defaultPart = $" = {param.DefaultValueExpression}";
            }
            else if (isOptional)
            {
                defaultPart = $" = {NullLiteral}";
            }

            var description = string.IsNullOrEmpty(param.Description)
                ? $"Parameter: {param.Name}"
                : param.Description!;
            var descAttr = $"[Description(\"{EscapeString(description)}\")] ";
            return $"{descAttr}{type} {EscapeIdentifier(param.Name)}{defaultPart}";
        }

        /// <summary>
        /// The text of a description for a C# string literal, on one line: C# ends a literal at a line or paragraph
        /// separator as at a line feed.
        /// </summary>
        private static string EscapeString(string s)
        {
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ").Replace("\r", "")
                .Replace(NextLine, ' ').Replace(LineSeparator, ' ').Replace(ParagraphSeparator, ' ');
        }

